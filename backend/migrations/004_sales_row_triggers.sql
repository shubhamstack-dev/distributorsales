-- 004: sales_row -> MAPPING_MASTER (every row) and MAPPING_MASTER_MID (Mid Month Y rows)
-- The app does all of this itself on every start (services/migrate.py adds the
-- columns, services/triggers.py drops and makes the triggers). This file is the
-- same SQL, for reading or for running by hand on MySQL 8. Generated from
-- services/triggers.py: change it there.

ALTER TABLE distributor ADD COLUMN DistId INT NULL;
UPDATE distributor SET DistId = 18671704 WHERE UPPER(Name) = 'PHARMACHEM' AND DistId IS NULL;
UPDATE distributor SET DistId = 16212104 WHERE UPPER(Name) = 'YETICHEM' AND DistId IS NULL;
UPDATE distributor SET DistId = 12664157 WHERE UPPER(Name) = 'GUNJESHWARI' AND DistId IS NULL;
ALTER TABLE sales_row ADD COLUMN CustomerId INT NULL, ADD COLUMN ProductId INT NULL;

DROP TRIGGER IF EXISTS trg_sales_row_to_mapping;

CREATE TRIGGER trg_sales_row_to_mapping AFTER INSERT ON sales_row FOR EACH ROW INSERT INTO MAPPING_MASTER (`DIST_ID`, `PRODUCT_NAME`, `PRODUCT_ID`, `PRODUCT_GROUP_ID`, `RATE`, `HQ_ID`, `MONTH`, `YEAR`, `TERRITORY_ID`, `PRODUCT_BRAND_ID`, `DIST_NAME`, `SALES_QTY`, `SALES_VALUE`, `CUSTOMER_NAME`, `CUSTOMER_MASTER_NAME`, `PRODUCT_GROUP_NAME`, `HQ_NAME`, `TERRITORY_NAME`, `PRODUCT_BRAND_NAME`, `INVOICE_NO`, `CUSTOMER_ID`, `FREE_QUANTITY`, `RETURN_QUANTITY`, `PRODUCT_MASTER_NAME`, `PRODUCT_BRAND_CATEGORY`)
SELECT d.DistId, NEW.ProductName, NEW.ProductId, COALESCE(p.PRODUCT_GROUP_ID, b.PRODUCT_GROUP_ID), NEW.Rate, a.HQ_ID, NEW.MonthName, NEW.Year, a.TERRITORY_ID, p.PRODUCT_BRAND_ID, NEW.DistributorName, CASE WHEN NEW.IsReturn = 1 THEN 0 ELSE NEW.Quantity END, NEW.Amount, NEW.CustomerName, c.CUSTOMER_NAME, g.Name, h.Name, t.Name, b.PRODUCT_BRAND_NAME, NEW.InvoiceNo, NEW.CustomerId, CASE WHEN NEW.IsReturn = 1 THEN 0 ELSE NEW.FreeQuantity END, CASE WHEN NEW.IsReturn = 1 THEN -ABS(NEW.Quantity) ELSE 0 END, p.SAP_PRODUCT_NAME, b.REPORTING
FROM batch bt
JOIN distributor d ON d.Id = bt.DistributorId
LEFT JOIN PRODUCT_MASTER p ON p.PRODUCT_ID = NEW.ProductId
LEFT JOIN PRODUCT_MASTER_BRAND b ON b.PRODUCT_BRAND_ID = p.PRODUCT_BRAND_ID
LEFT JOIN CUSTOMER_MASTER c ON c.CUSTOMER_ID = NEW.CustomerId
LEFT JOIN CUSTOMER_TERR_ASSIGNMENT a ON a.ID = (
    SELECT MIN(x.ID) FROM CUSTOMER_TERR_ASSIGNMENT x
    WHERE x.CUSTOMER_ID = NEW.CustomerId AND x.PRODUCT_GROUP_ID = COALESCE(p.PRODUCT_GROUP_ID, b.PRODUCT_GROUP_ID))
LEFT JOIN md_headquarter h ON h.LegacyId = a.HQ_ID
LEFT JOIN md_territory t ON t.LegacyId = a.TERRITORY_ID
LEFT JOIN md_product_group g ON g.LegacyId = COALESCE(p.PRODUCT_GROUP_ID, b.PRODUCT_GROUP_ID)
WHERE bt.Id = NEW.BatchId;

DROP TRIGGER IF EXISTS trg_sales_row_to_mapping_mid;

CREATE TRIGGER trg_sales_row_to_mapping_mid AFTER INSERT ON sales_row FOR EACH ROW INSERT INTO MAPPING_MASTER_MID (`DIST_ID`, `PRODUCT_NAME`, `PRODUCT_ID`, `PRODUCT_GROUP_ID`, `RATE`, `HQ_ID`, `MONTH`, `YEAR`, `TERRITORY_ID`, `PRODUCT_BRAND_ID`, `DIST_NAME`, `SALES_QTY`, `SALES_VALUE`, `CUSTOMER_NAME`, `CUSTOMER_MASTER_NAME`, `PRODUCT_GROUP_NAME`, `HQ_NAME`, `TERRITORY_NAME`, `PRODUCT_BRAND_NAME`, `INVOICE_NO`, `CUSTOMER_ID`, `FREE_QUANTITY`, `RETURN_QUANTITY`, `PRODUCT_MASTER_NAME`, `PRODUCT_BRAND_CATEGORY`)
SELECT d.DistId, NEW.ProductName, NEW.ProductId, COALESCE(p.PRODUCT_GROUP_ID, b.PRODUCT_GROUP_ID), NEW.Rate, a.HQ_ID, NEW.MonthName, NEW.Year, a.TERRITORY_ID, p.PRODUCT_BRAND_ID, NEW.DistributorName, CASE WHEN NEW.IsReturn = 1 THEN 0 ELSE NEW.Quantity END, NEW.Amount, NEW.CustomerName, c.CUSTOMER_NAME, g.Name, h.Name, t.Name, b.PRODUCT_BRAND_NAME, NEW.InvoiceNo, NEW.CustomerId, CASE WHEN NEW.IsReturn = 1 THEN 0 ELSE NEW.FreeQuantity END, CASE WHEN NEW.IsReturn = 1 THEN -ABS(NEW.Quantity) ELSE 0 END, p.SAP_PRODUCT_NAME, b.REPORTING
FROM batch bt
JOIN distributor d ON d.Id = bt.DistributorId
LEFT JOIN PRODUCT_MASTER p ON p.PRODUCT_ID = NEW.ProductId
LEFT JOIN PRODUCT_MASTER_BRAND b ON b.PRODUCT_BRAND_ID = p.PRODUCT_BRAND_ID
LEFT JOIN CUSTOMER_MASTER c ON c.CUSTOMER_ID = NEW.CustomerId
LEFT JOIN CUSTOMER_TERR_ASSIGNMENT a ON a.ID = (
    SELECT MIN(x.ID) FROM CUSTOMER_TERR_ASSIGNMENT x
    WHERE x.CUSTOMER_ID = NEW.CustomerId AND x.PRODUCT_GROUP_ID = COALESCE(p.PRODUCT_GROUP_ID, b.PRODUCT_GROUP_ID))
LEFT JOIN md_headquarter h ON h.LegacyId = a.HQ_ID
LEFT JOIN md_territory t ON t.LegacyId = a.TERRITORY_ID
LEFT JOIN md_product_group g ON g.LegacyId = COALESCE(p.PRODUCT_GROUP_ID, b.PRODUCT_GROUP_ID)
WHERE bt.Id = NEW.BatchId AND NEW.MidMonth = 'Y';
